/* ------------------------------------------------------------------------- */
/* Runtime validation helpers                                                */
/* ------------------------------------------------------------------------- */

/** Result of {@link validatePacket}. */
export type ValidationResult =
  | { ok: true; packet: Packet }
  | { ok: false; code: 400 | 413; reason: string };

const PACKET_TYPES: readonly PacketType[] = [
  "msg",
  "cb",
  "status",
  "ping",
  "pong",
  "err",
];

const ERROR_CODES: readonly ErrCode[] = [400, 401, 413, 429];

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function utf8Length(value: string): number {
  return new TextEncoder().encode(value).length;
}

function fail(reason: string, code: 400 | 413 = 400): ValidationResult {
  return { ok: false, code, reason };
}

function validateKeyboard(
  raw: unknown,
  errors: string[],
): IBKeyboard | undefined {
  if (raw === undefined) return undefined;
  if (!Array.isArray(raw)) {
    errors.push("kb must be an array of rows");
    return undefined;
  }
  if (raw.length > MAX_KB_ROWS) {
    errors.push(`kb must have at most ${MAX_KB_ROWS} rows`);
    return undefined;
  }

  const keyboard: IBKeyboard = [];
  for (const [rowIndex, row] of raw.entries()) {
    if (!Array.isArray(row) || row.length === 0) {
      errors.push(`kb[${rowIndex}] must be a non-empty array of buttons`);
      return undefined;
    }
    if (row.length > MAX_KB_COLS) {
      errors.push(`kb[${rowIndex}] must have at most ${MAX_KB_COLS} buttons`);
      return undefined;
    }

    const buttons: IBButton[] = [];
    for (const [buttonIndex, button] of row.entries()) {
      if (
        !isRecord(button) ||
        typeof button.t !== "string" ||
        button.t.length === 0 ||
        typeof button.d !== "string" ||
        button.d.length === 0
      ) {
        errors.push(`kb[${rowIndex}][${buttonIndex}] must be { t: string, d: string }`);
        return undefined;
      }
      buttons.push({ t: button.t, d: button.d });
    }
    keyboard.push(buttons);
  }
  return keyboard;
}

function validateMsg(raw: Record<string, unknown>): ValidationResult {
  if (typeof raw.id !== "string" || raw.id.length === 0) {
    return fail("msg.id must be a non-empty string");
  }
  if (raw.from !== "dev" && raw.from !== "usr") {
    return fail('msg.from must be "dev" or "usr"');
  }
  if (typeof raw.text !== "string") {
    return fail("msg.text must be a string");
  }
  if (utf8Length(raw.text) > MAX_TEXT_BYTES) {
    return fail(`msg.text exceeds ${MAX_TEXT_BYTES} bytes`);
  }
  if (
    raw.ts !== undefined &&
    (typeof raw.ts !== "number" || !Number.isInteger(raw.ts) || raw.ts < 0)
  ) {
    return fail("msg.ts must be a non-negative integer (unix seconds)");
  }
  if (raw.edit !== undefined && typeof raw.edit !== "boolean") {
    return fail("msg.edit must be a boolean");
  }

  const errors: string[] = [];
  const kb = validateKeyboard(raw.kb, errors);
  if (errors.length > 0) return fail(errors[0] ?? "invalid kb");

  const packet: MsgPacket = {
    v: PROTOCOL_VERSION,
    type: "msg",
    id: raw.id,
    from: raw.from,
    text: raw.text,
  };
  if (raw.ts !== undefined) packet.ts = raw.ts;
  if (raw.edit !== undefined) packet.edit = raw.edit;
  if (kb) packet.kb = kb;
  return { ok: true, packet };
}

function validateCb(raw: Record<string, unknown>): ValidationResult {
  if (typeof raw.id !== "string" || raw.id.length === 0) {
    return fail("cb.id must be a non-empty string");
  }
  if (raw.from !== "usr") {
    return fail('cb.from must be "usr"');
  }
  if (typeof raw.d !== "string" || raw.d.length === 0) {
    return fail("cb.d must be a non-empty string");
  }
  return {
    ok: true,
    packet: { v: PROTOCOL_VERSION, type: "cb", id: raw.id, from: "usr", d: raw.d },
  };
}

function validateStatus(raw: Record<string, unknown>): ValidationResult {
  if (typeof raw.dev_online !== "boolean") {
    return fail("status.dev_online must be a boolean");
  }
  if (
    typeof raw.last_seen !== "number" ||
    !Number.isInteger(raw.last_seen) ||
    raw.last_seen < 0
  ) {
    return fail("status.last_seen must be a non-negative integer (unix seconds)");
  }
  return {
    ok: true,
    packet: {
      v: PROTOCOL_VERSION,
      type: "status",
      dev_online: raw.dev_online,
      last_seen: raw.last_seen,
    },
  };
}

function validateErr(raw: Record<string, unknown>): ValidationResult {
  if (
    typeof raw.code !== "number" ||
    !ERROR_CODES.includes(raw.code as ErrCode)
  ) {
    return fail("err.code must be one of 400, 401, 413, 429");
  }
  if (typeof raw.msg !== "string") {
    return fail("err.msg must be a string");
  }
  return {
    ok: true,
    packet: { v: PROTOCOL_VERSION, type: "err", code: raw.code as ErrCode, msg: raw.msg },
  };
}

/**
 * Validates an unknown value against PROTOCOL.md and narrows it to a packet.
 * The transport-level limit (1024 bytes for the whole packet) can be enforced
 * by passing the raw byte length as `byteLength`.
 */
export function validatePacket(raw: unknown, byteLength?: number): ValidationResult {
  if (byteLength !== undefined && byteLength > MAX_PACKET_SIZE) {
    return fail(`packet exceeds ${MAX_PACKET_SIZE} bytes`, 413);
  }
  if (!isRecord(raw)) return fail("packet must be a JSON object");
  if (raw.v !== PROTOCOL_VERSION) {
    return fail(`unsupported protocol version (expected ${PROTOCOL_VERSION})`);
  }

  if (typeof raw.type !== "string" || !PACKET_TYPES.includes(raw.type as PacketType)) {
    return fail("unknown packet type");
  }
  const type = raw.type as PacketType;

  switch (type) {
    case "msg":
      return validateMsg(raw);
    case "cb":
      return validateCb(raw);
    case "status":
      return validateStatus(raw);
    case "err":
      return validateErr(raw);
    case "ping":
    case "pong":
      return { ok: true, packet: { v: PROTOCOL_VERSION, type } };
  }
}

/** Type guard: `raw` is any valid protocol packet. */
export function isPacket(raw: unknown): raw is Packet {
  return validatePacket(raw).ok;
}

/** Type guard: `raw` is a valid "msg" packet. */
export function isMsgPacket(raw: unknown): raw is MsgPacket {
  const result = validatePacket(raw);
  return result.ok && result.packet.type === "msg";
}

/** Type guard: `raw` is a valid "cb" packet. */
export function isCbPacket(raw: unknown): raw is CbPacket {
  const result = validatePacket(raw);
  return result.ok && result.packet.type === "cb";
}

/** Type guard: `raw` is a valid "status" packet. */
export function isStatusPacket(raw: unknown): raw is StatusPacket {
  const result = validatePacket(raw);
  return result.ok && result.packet.type === "status";
}

/** Type guard: `raw` is a valid "err" packet. */
export function isErrPacket(raw: unknown): raw is ErrPacket {
  const result = validatePacket(raw);
  return result.ok && result.packet.type === "err";
}

/** Builds a "status" packet (§2.3). */
export function buildStatusPacket(devOnline: boolean, lastSeen: number): StatusPacket {
  return { v: PROTOCOL_VERSION, type: "status", dev_online: devOnline, last_seen: lastSeen };
}

/** Builds an "err" packet (§2.4). */
export function buildErrPacket(code: ErrCode, msg: string): ErrPacket {
  return { v: PROTOCOL_VERSION, type: "err", code, msg };
}
