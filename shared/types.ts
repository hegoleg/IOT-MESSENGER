/**
 * IoT-Messenger wire protocol, version 1.
 *
 * This file is the TypeScript mirror of PROTOCOL.md (the single source of
 * truth). Packet shapes, field names and limits MUST match the document:
 * protocol changes start in PROTOCOL.md, then land here, then in server/,
 * web-app/ and firmware/.
 */

/** Protocol version carried in the `v` field of every packet. */
export const PROTOCOL_VERSION = 1 as const;

/** Maximum size of a whole JSON packet in bytes (UTF-8). PROTOCOL.md §2. */
export const MAX_PACKET_SIZE = 1024;

/** Maximum size of the `text` field in bytes (UTF-8). PROTOCOL.md §2.1. */
export const MAX_TEXT_BYTES = 512;

/** Inline keyboard limits: rows and buttons per row. PROTOCOL.md §2.1. */
export const MAX_KB_ROWS = 3;
export const MAX_KB_COLS = 3;

/** Number of messages kept per device token. PROTOCOL.md §3.1. */
export const HISTORY_LIMIT = 50;

/** Heartbeat timing. PROTOCOL.md §2.4. */
export const PING_INTERVAL_MS = 25_000;
export const PONG_TIMEOUT_MS = 5_000;
export const RECONNECT_DELAY_MS = 3_000;

/** Cloud WebSocket endpoint path. PROTOCOL.md §1.1. */
export const WS_PATH = "/ws";

/** Protocol version literal. */
export type ProtocolVersion = typeof PROTOCOL_VERSION;

/** Connection role: "dev" — microcontroller, "usr" — mobile/web client. */
export type Role = "dev" | "usr";

/** All packet types defined by PROTOCOL.md §2. */
export type PacketType = "msg" | "cb" | "status" | "ping" | "pong" | "err";

/** Error codes from PROTOCOL.md §2.4. */
export type ErrCode = 400 | 401 | 413 | 429;

/** One inline keyboard button (§2.1). */
export interface IBButton {
  /** Button label. */
  t: string;
  /** callback_data returned to the device when the button is pressed. */
  d: string;
}

/** Inline keyboard: up to MAX_KB_ROWS rows of up to MAX_KB_COLS buttons. */
export type IBKeyboard = IBButton[][];

/** Text message with an optional inline keyboard (type "msg", §2.1). */
export interface MsgPacket {
  v: ProtocolVersion;
  type: "msg";
  /** Unique message id; the server keeps it stable for edits. */
  id: string;
  /** Sender: "dev" (board) or "usr" (phone). */
  from: Role;
  /** Unix timestamp in seconds; 0/undefined means "server fills in now". */
  ts?: number;
  /** Message text or command, at most MAX_TEXT_BYTES bytes. */
  text: string;
  /** Update the existing message with the same id instead of adding a new one. */
  edit?: boolean;
  kb?: IBKeyboard;
}

/** Inline button press (type "cb", §2.2). */
export interface CbPacket {
  v: ProtocolVersion;
  type: "cb";
  /** Id of the message that owns the pressed button. */
  id: string;
  from: "usr";
  /** callback_data of the pressed button. */
  d: string;
}

/** Peer online state generated by the relay (type "status", §2.3). */
export interface StatusPacket {
  v: ProtocolVersion;
  type: "status";
  dev_online: boolean;
  last_seen: number;
}

/** Heartbeat request (type "ping", §2.4). */
export interface PingPacket {
  v: ProtocolVersion;
  type: "ping";
}

/** Heartbeat reply (type "pong", §2.4). */
export interface PongPacket {
  v: ProtocolVersion;
  type: "pong";
}

/** Protocol error (type "err", §2.4). */
export interface ErrPacket {
  v: ProtocolVersion;
  type: "err";
  code: ErrCode;
  msg: string;
}

/** Any packet that can travel over the wire. */
export type Packet =
  | MsgPacket
  | CbPacket
  | StatusPacket
  | PingPacket
  | PongPacket
  | ErrPacket;

